// Development-only generator for the immutable water-mark scene.
// Run deliberately when redesigning the field; the browser never imports this file.
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const OUT = resolve(import.meta.dirname, '../src/editor/waveSceneData.ts')
const WIDTH = 2800
const ROWS = 12
const ROW_H = 140
const INTRO_MS = 1800
const SCROLL_PERIOD_PX = 2240
const MIN_X_GAP = 180

function rng(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const random = rng(0x1a6b7c4d)
const round = (n, p = 2) => Number(n.toFixed(p))
const ringDistance = (a, b) => Math.min(Math.abs(a - b), WIDTH - Math.abs(a - b))

function wavePoint(group, row, x) {
  const phase = ((x % ROW_H) + ROW_H) % ROW_H
  const second = phase >= 70
  const t = (second ? phase - 70 : phase) / 70
  const localY = second ? 22 + 36 * t - 36 * t * t : 22 - 36 * t + 36 * t * t
  const slope = second ? (36 - 72 * t) / 70 : (-36 + 72 * t) / 70
  return {
    y: round(row * ROW_H + localY + (group === 'b' ? 70 : 0)),
    angle: round(Math.atan(slope) * 180 / Math.PI),
  }
}

function spacedXs(count) {
  const xs = []
  const bin = WIDTH / count
  for (let i = 0; i < count; i++) {
    let best = null
    let bestGap = -1
    for (let attempt = 0; attempt < 48; attempt++) {
      const x = round(i * bin + bin * (0.15 + random() * 0.7))
      const gap = xs.length ? Math.min(...xs.map((old) => ringDistance(x, old))) : WIDTH
      if (gap >= MIN_X_GAP) { best = x; break }
      if (gap > bestGap) { best = x; bestGap = gap }
    }
    xs.push(best)
  }
  // Seeded shuffle means neighbouring time entries do not march left-to-right.
  for (let i = xs.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1)); [xs[i], xs[j]] = [xs[j], xs[i]]
  }
  return xs
}

const intro = []
const scroll = []
let id = 0
for (let row = 0; row < ROWS; row++) {
  for (const group of ['a', 'b']) {
    const xs = spacedXs(8)
    for (let i = 0; i < 5; i++) {
      const x = xs[i]
      const pt = wavePoint(group, row, x)
      const kind = i === 4 ? 'spark' : 'dash'
      const startMs = (row + i) % 7 === 0 ? 0 : Math.round(90 + random() * 1050)
      const life = kind === 'spark' ? 190 + Math.round(random() * 210) : 430 + Math.round(random() * 350)
      intro.push({
        id: `i${id++}`, kind, group, row, x, y: kind === 'spark' ? round(pt.y + 14 + random() * 13) : pt.y,
        angle: kind === 'dash' ? pt.angle : 0,
        size: kind === 'dash' ? Math.round(12 + random() * 17) : Math.round(7 + random() * 5),
        opacity: round(kind === 'dash' ? 0.3 + random() * 0.17 : 0.64 + random() * 0.28),
        startMs, endMs: Math.min(INTRO_MS - 80, startMs + life),
      })
    }
    for (let i = 5; i < 8; i++) {
      const x = xs[i]
      const pt = wavePoint(group, row, x)
      scroll.push({
        id: `s${id++}`, group, row, x, y: pt.y, angle: pt.angle,
        size: Math.round(13 + random() * 17), opacity: round(0.3 + random() * 0.16),
        phasePx: Math.round(random() * SCROLL_PERIOD_PX),
        spanPx: Math.round(430 + random() * 260),
        overlapMs: Math.round(850 + random() * 650),
      })
    }
  }
}

const text = `// GENERATED by scripts/generate-wave-scene.mjs — do not hand-edit coordinates.\n`
  + `// One fixed scene ships to every client; there is no runtime randomness or server feed.\n\n`
  + `export const WAVE_SCENE_WIDTH = ${WIDTH}\n`
  + `export const WAVE_SCENE_HEIGHT = ${ROWS * ROW_H}\n`
  + `export const WAVE_INTRO_MS = ${INTRO_MS}\n`
  + `export const WAVE_SCROLL_PERIOD_PX = ${SCROLL_PERIOD_PX}\n\n`
  + `export type WaveIntroMark = {\n  id: string\n  kind: 'dash' | 'spark'\n  group: 'a' | 'b'\n  row: number\n  x: number\n  y: number\n  angle: number\n  size: number\n  opacity: number\n  startMs: number\n  endMs: number\n}\n\n`
  + `export type WaveScrollMark = {\n  id: string\n  group: 'a' | 'b'\n  row: number\n  x: number\n  y: number\n  angle: number\n  size: number\n  opacity: number\n  phasePx: number\n  spanPx: number\n  overlapMs: number\n}\n\n`
  + `export const WAVE_SCENE = Object.freeze({\n  intro: ${JSON.stringify(intro, null, 2)},\n  scroll: ${JSON.stringify(scroll, null, 2)},\n}) satisfies { intro: readonly WaveIntroMark[]; scroll: readonly WaveScrollMark[] }\n`

writeFileSync(OUT, text)
console.log(`wrote ${OUT}: ${intro.length} one-shot intro marks, ${scroll.length} scroll-loop marks`)
